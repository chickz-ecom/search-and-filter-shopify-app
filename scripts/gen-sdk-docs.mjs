// Sinh docs/developers/sdk-reference.md từ packages/storefront-sdk/dist/types.d.ts (hợp đồng SDK v1).
// `node scripts/gen-sdk-docs.mjs --check` → exit 1 nếu file docs lệch với .d.ts (dùng trong CI / check).
import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

const SRC = "packages/storefront-sdk/dist/types.d.ts";
const OUT = "docs/developers/sdk-reference.md";
const pkg = JSON.parse(readFileSync("packages/storefront-sdk/package.json", "utf8"));
const sf = ts.createSourceFile(SRC, readFileSync(SRC, "utf8"), ts.ScriptTarget.Latest, true);

const doc = (node) =>
  ts
    .getJSDocCommentsAndTags(node)
    .map((d) =>
      typeof d.comment === "string" ? d.comment : (ts.getTextOfJSDocComment(d.comment) ?? ""),
    )
    .join(" ")
    .trim();
const text = (n) => n.getText(sf).replace(/\s+/g, " ").replace(/;\s*}/g, " }");
const cell = (s) => s.replace(/\|/g, "\\|");

// Thứ tự: SDK trước (thứ dev dùng nhiều nhất), rồi params/response, rồi phần còn lại theo thứ tự khai báo.
const FIRST = [
  "SearchAppSDK",
  "SearchParams",
  "CollectionParams",
  "SearchResponse",
  "SuggestResponse",
  "Product",
];
const decls = sf.statements.filter(
  (s) => ts.isInterfaceDeclaration(s) || ts.isTypeAliasDeclaration(s),
);
decls.sort((a, b) => {
  const ia = FIRST.indexOf(a.name.text);
  const ib = FIRST.indexOf(b.name.text);
  return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib);
});

const out = [
  "# SDK reference (`window.SearchApp`)",
  "",
  `<!-- Generated by scripts/gen-sdk-docs.mjs from ${SRC}. Do not edit by hand: run \`npm run docs:sdk\`. -->`,
  "",
  `SDK version: **${pkg.version}**. Types are published as \`${pkg.name}\` (\`${pkg.types}\`).`,
  "",
  "## Contents",
  "",
  ...decls.map((d) => `- [\`${d.name.text}\`](#${d.name.text.toLowerCase()})`),
  "",
];

for (const d of decls) {
  out.push(`## \`${d.name.text}\``, "");
  const desc = doc(d);
  if (desc) out.push(desc, "");
  if (ts.isTypeAliasDeclaration(d)) {
    out.push("```ts", text(d), "```", "");
    continue;
  }
  if (d.heritageClauses?.length)
    out.push(
      `Extends ${d.heritageClauses.map((h) => `\`${text(h).replace(/^extends /, "")}\``).join(", ")}.`,
      "",
    );
  const methods = d.members.filter((m) => ts.isMethodSignature(m));
  const props = d.members.filter((m) => !ts.isMethodSignature(m));
  if (props.length) {
    out.push("| Property | Type | Description |", "|---|---|---|");
    for (const m of props) {
      if (ts.isIndexSignatureDeclaration(m)) {
        out.push(
          `| \`[${text(m.parameters[0])}]\` | \`${cell(text(m.type))}\` | ${cell(doc(m))} |`,
        );
        continue;
      }
      const name = `${m.modifiers?.some((x) => x.kind === ts.SyntaxKind.ReadonlyKeyword) ? "readonly " : ""}${m.name.getText(sf)}${m.questionToken ? "?" : ""}`;
      out.push(
        `| \`${name}\` | \`${cell(m.type ? text(m.type) : "unknown")}\` | ${cell(doc(m))} |`,
      );
    }
    out.push("");
  }
  if (methods.length) {
    out.push("| Method | Description |", "|---|---|");
    for (const m of methods)
      out.push(`| \`${cell(text(m).replace(/;$/, ""))}\` | ${cell(doc(m))} |`);
    out.push("");
  }
}

const md = out.join("\n");
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(OUT, "utf8");
  } catch {
    /* thiếu file = lệch */
  }
  if (cur !== md) {
    console.error(`${OUT} is out of date with ${SRC}. Run: npm run docs:sdk`);
    process.exit(1);
  }
  console.log(`${OUT} up to date`);
} else {
  writeFileSync(OUT, md);
  console.log(`wrote ${OUT} (${decls.length} types)`);
}
